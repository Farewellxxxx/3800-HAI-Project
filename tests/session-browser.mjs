import {createRequire} from 'node:module';
import {mkdir,writeFile,readFile} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
const {Midi}=createRequire(new URL('../web/optimized/package.json',import.meta.url))('@tonejs/midi');
const root=path.resolve(import.meta.dirname,'..'),base=process.env.INPUT_LAB_URL||'http://127.0.0.1:4186';
const out=path.join(root,'tmp/session-browser');await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1400,height:1000}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
async function render(selector,label){
  const response=page.waitForResponse(r=>r.url()===base+'/api/session/render');
  await page.locator(selector).click();
  const r=await response,result=await r.json();
  assert.equal(r.status(),200,result.error);
  await page.waitForFunction(id=>document.querySelector('#outputs article')?.dataset.request===id,result.request_id);
  await writeFile(path.join(out,label+'.mid'),Buffer.from(result.midi,'base64'));
  await writeFile(path.join(out,label+'.wav'),Buffer.from(result.wav,'base64'));
  const {midi,wav,...receipt}=result;
  await writeFile(path.join(out,label+'.json'),JSON.stringify(receipt,null,2));
  const parsed=new Midi(Buffer.from(midi,'base64'));
  const tracks=Object.fromEntries(parsed.tracks.filter(t=>t.notes.length).map(t=>[t.channel===4?'lead':t.channel===2?'bass':t.channel===1?'keys':'drums',t.notes.map(n=>[n.midi,n.ticks,n.durationTicks,n.velocity])]));
  assert.equal(Buffer.from(wav,'base64').toString('ascii',0,4),'RIFF');
  return {result,tracks};
}
try{
  const response=await page.goto(base+'/session.html');
  assert.equal(response.status(),200,'session workbench exists');
  await page.waitForFunction(()=>document.querySelector('#session-state').dataset.ready==='true');
  const rhythm=page.frameLocator('#rhythm-frame');
  await rhythm.locator('#example').click();
  await rhythm.locator('#analyze').click();
  await rhythm.locator('[data-add-session]').waitFor({state:'visible',timeout:90000});
  await rhythm.locator('[data-add-session]').click();
  await page.waitForFunction(()=>document.querySelector('#rhythm-summary').dataset.loaded==='true');
  await page.selectOption('#tempo-source','rhythm');
  await page.selectOption('#key','0:major');
  await page.locator('[data-tab="humming"]').click();
  const hum=page.frameLocator('#humming-frame');
  await hum.locator('#example').click();
  await hum.locator('#convert').click();
  await hum.locator('[data-add-session]').waitFor({state:'visible',timeout:90000});
  await hum.locator('[data-add-session]').click();
  await page.waitForFunction(()=>document.querySelector('#humming-summary').dataset.loaded==='true');
  assert(await page.locator('#render').isDisabled(),'separate recordings require alignment confirmation');
  await page.locator('#alignment-confirmed').check();
  const first=await render('#render','combined');
  assert.equal(first.result.settings.tempo_source,'rhythm');
  assert.deepEqual(first.result.state.harmony.key,{tonic:0,mode:'major'});
  assert.deepEqual(first.tracks.lead.map(n=>n[0]),[60,64,67,64,62]);
  const strong=await render('[data-command="鼓更有力"]','strong-drums');
  for(const name of ['lead','bass','keys'])assert.deepEqual(first.tracks[name],strong.tracks[name]);
  assert.notDeepEqual(first.tracks.drums,strong.tracks.drums);
  assert.equal(await page.locator('#outputs article').count(),2);
  const removed=await render('[data-command="去掉贝斯"]','no-bass');
  assert.equal(removed.tracks.bass,undefined);
  const restored=await render('[data-command="加上贝斯"]','restored-bass');
  assert.deepEqual(restored.tracks.bass,first.tracks.bass);
  await page.locator('#text-command').fill('鼓更有力，变成一只猫');
  const rejected=page.waitForResponse(r=>r.url().endsWith('/api/session/render'));
  await page.locator('#send-command').click();
  assert.equal((await rejected).status(),400);
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('未执行'));
  assert.equal(await page.locator('#outputs article').count(),2);
  await page.selectOption('#tempo-source','manual');await page.locator('#bpm').fill('120');
  await page.locator('#melody-origin').fill('0.1');await page.locator('#placement').fill('2');
  await page.locator('#alignment-confirmed').check();
  const aligned=await render('#render','aligned');
  const alignedMidi=new Midi(Buffer.from(aligned.result.midi,'base64'));
  const lead=alignedMidi.tracks.find(t=>t.channel===4).notes;
  const source=aligned.result.inputs.humming.payload.melody.notes;
  lead.forEach((n,i)=>{assert.equal(n.midi,source[i].pitchMidi);assert(Math.abs(n.time-source[i].startSec-.9)<.003);assert(Math.abs(n.duration-source[i].durationSec)<.003);});
  await page.selectOption('#key','unknown');
  const unknown=await render('#render','unknown-key');assert.deepEqual(Object.keys(unknown.tracks).sort(),['drums','lead']);
  await page.locator('#outputs audio').first().evaluate(a=>a.play());
  await hum.locator('#original').evaluate(a=>a.play());
  await page.waitForFunction(()=>document.querySelector('#outputs audio').paused);
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile layout fits');
  await page.screenshot({path:path.join(out,'mobile.png'),fullPage:true});
  await page.setViewportSize({width:1400,height:1000});
  await page.screenshot({path:path.join(out,'session.png'),fullPage:true});
  const sid=unknown.result.session_id;
  await page.locator('#new-session').click();
  await page.waitForFunction(id=>document.querySelector('#session-state').dataset.session!==id,sid);
  assert.equal(await page.locator('#outputs article').count(),0);
  assert(await page.locator('#render').isDisabled());
  assert(await hum.locator('#download-original').getAttribute('href'),'reset preserves original recording in input panel');
  assert.deepEqual(errors,[]);
  await writeFile(path.join(out,'report.json'),JSON.stringify({combined:true,controls:true,alignment:true,unknownKey:true,reset:true,mobile:true,pageErrors:errors},null,2));
  console.log('Session browser flow passed: actual Basic Pitch, rhythm, FluidSynth, MIDI and WAV.');
} finally {await browser.close();}
